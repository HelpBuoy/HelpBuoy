// KnownCode reports whether code is in Codes.
func KnownCode(code string) bool {
	_, ok := codeSet[code]
	return ok
}

var codeSet = func() map[string]struct{} {
	m := make(map[string]struct{}, len(Codes))
	for _, c := range Codes {
		m[c] = struct{}{}
	}
	return m
}()
